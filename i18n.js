const LANGS = ['th', 'en', 'zh'];
const LANG_STORE = 'suitcube_lang';

// ลำดับ: ?lang= → ที่เคยเลือก → ภาษาของเครื่อง (มีไทยในรายการ = ไทย · จีนเป็นภาษาแรก = จีน · นอกนั้นอังกฤษ)
function detectLang() {
  const q = new URLSearchParams(location.search).get('lang');
  if (q) {
    const l = q.toLowerCase().startsWith('zh') ? 'zh' : q.toLowerCase().slice(0, 2);
    if (LANGS.includes(l)) return l;
  }
  try {
    const saved = localStorage.getItem(LANG_STORE);
    if (LANGS.includes(saved)) return saved;
  } catch { /* โหมดส่วนตัว/ปิด storage */ }
  const prefs = (navigator.languages?.length ? navigator.languages : [navigator.language || 'th']).map(l => l.toLowerCase());
  if (prefs.some(l => l.startsWith('th'))) return 'th';
  if (prefs[0].startsWith('zh')) return 'zh';
  return 'en';
}

let LANG = detectLang();

// t('key', {ตัวแปร}) — คืน string/array/object ตามที่ประกาศไว้ ถ้าภาษานั้นไม่มี key ใช้ภาษาไทย
function t(key, vars) {
  let s = I18N[LANG][key];
  if (s === undefined) s = I18N.th[key];
  if (typeof s === 'string' && vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
  return s;
}

// ข้อความที่อยู่ใน index.html: data-i18n="key" (ข้อความ) · data-i18n-aria="key" (aria-label)
function applyStaticI18n() {
  document.documentElement.lang = t('htmlLang');
  document.title = t('title');
  document.querySelector('meta[name="description"]')?.setAttribute('content', t('desc'));
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  // ฟอนต์จีนโหลดเฉพาะเมื่อเลือกภาษาจีน (Prompt ไม่มีตัวอักษรจีน)
  if (LANG === 'zh' && !document.querySelector('#font-zh')) {
    const link = document.createElement('link');
    link.id = 'font-zh';
    link.rel = 'stylesheet';
    link.href = 'https://fonts.googleapis.com/css2?family=Noto+Sans+SC:wght@400;500;700&display=swap';
    document.head.append(link);
  }
}
